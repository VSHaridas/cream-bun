import type { BriefDraft } from "@/lib/llm/contract";
import { inr } from "@/lib/utils";

/**
 * Brief export.
 *
 * The builder produced a brief that existed only in component state. There was
 * nothing to send to a creator, nothing to attach to an email, and nothing to
 * re-read after the tab closed. These renderers are deliberately plain: a brief
 * a brand sends out is read in email clients, Slack and Notion, so Markdown
 * that survives being pasted is worth more than a PDF that only this app can
 * render.
 */

export interface ExportTurn {
  role: string;
  text: string;
}

function bullets(values: string[] | undefined, empty = "—") {
  const list = (values ?? []).filter(Boolean);
  return list.length ? list.map((v) => `- ${v}`).join("\n") : empty;
}

function section(title: string, body: string) {
  return body && body !== "—" ? `## ${title}\n\n${body}\n` : "";
}

/** Full brief as Markdown, including the conversation that produced it. */
export function renderBriefMarkdown(
  code: string,
  draft: BriefDraft,
  turns: ExportTurn[] = [],
): string {
  const lines: string[] = [`# ${code || "Untitled brief"}`, ""];

  lines.push(section("Objective", draft.campaignObjective || "—"));
  lines.push(section("Audience", draft.audience || "—"));

  lines.push(
    section(
      "Budget",
      draft.budgetMaxInr
        ? `${inr(draft.budgetMinInr)} — ${inr(draft.budgetMaxInr)}`
        : "—",
    ),
  );

  lines.push(
    section(
      "Deliverables",
      draft.deliverables.length
        ? draft.deliverables
            .map(
              (d) =>
                `- ${d.quantity} × ${d.contentType}${
                  d.durationSeconds ? ` (${Math.round(d.durationSeconds)}s each)` : ""
                }${d.aspectRatio ? ` · ${d.aspectRatio}` : ""}${
                  d.notes ? ` — ${d.notes}` : ""
                }`,
            )
            .join("\n")
        : "—",
    ),
  );

  lines.push(section("Tone", bullets(draft.tone)));
  lines.push(section("Style", bullets(draft.styleTags)));
  lines.push(section("Avoid", bullets(draft.excludedStyles)));
  lines.push(section("References", bullets(draft.referenceNotes)));

  lines.push(
    section(
      "Format",
      [
        draft.contentTypes.length ? `- Content: ${draft.contentTypes.join(", ")}` : "",
        draft.aspectRatios.length ? `- Aspect: ${draft.aspectRatios.join(", ")}` : "",
        draft.targetChannels.length ? `- Channels: ${draft.targetChannels.join(", ")}` : "",
      ]
        .filter(Boolean)
        .join("\n") || "—",
    ),
  );

  lines.push(
    section(
      "Terms",
      [
        `- Turnaround: ${draft.turnaroundDays || "—"} days`,
        `- Revisions included: ${draft.revisionsIncluded ?? "—"}`,
        `- Concept rounds: ${draft.conceptRoundsIncluded ?? "—"}`,
        `- Licence: ${draft.commercialUse?.licenseType ?? "—"}${
          draft.commercialUse?.territory ? ` · ${draft.commercialUse.territory}` : ""
        }`,
      ].join("\n"),
    ),
  );

  lines.push(section("Original request", draft.rawIdea || "—"));

  if (turns.length) {
    lines.push("## Conversation\n");
    lines.push(
      turns
        .map((t) => `**${t.role === "user" ? "Brand" : "CREAM"}** · ${t.text}`)
        .join("\n\n"),
    );
    lines.push("");
  }

  lines.push("---");
  lines.push(`_Generated by CREAM · ${code || "unsaved draft"}_`);

  return lines.filter(Boolean).join("\n");
}

/** Flat plain-text version, for pasting into email or Slack. */
export function briefAsText(code: string, draft: BriefDraft): string {
  return renderBriefMarkdown(code, draft)
    .replace(/^#{1,3}\s*/gm, "")
    .replace(/\*\*(.+?)\*\*/g, "$1")
    .replace(/^-\s*/gm, "• ")
    .replace(/^_.*_$/gm, "");
}

/** Triggers a client-side download. No server round trip. */
export function downloadText(filename: string, contents: string, type = "text/markdown") {
  const blob = new Blob([contents], { type: `${type};charset=utf-8` });
  const url = URL.createObjectURL(blob);
  const a = document.createElement("a");
  a.href = url;
  a.download = filename.endsWith(".md") ? filename : `${filename}.md`;
  document.body.appendChild(a);
  a.click();
  a.remove();
  // Revoking immediately can cancel the download in some browsers.
  setTimeout(() => URL.revokeObjectURL(url), 1_000);
}

export async function copyToClipboard(contents: string) {
  if (navigator.clipboard?.writeText) {
    await navigator.clipboard.writeText(contents);
    return true;
  }
  // Non-secure contexts and older browsers have no async clipboard.
  const ta = document.createElement("textarea");
  ta.value = contents;
  ta.style.position = "fixed";
  ta.style.opacity = "0";
  document.body.appendChild(ta);
  ta.select();
  const ok = document.execCommand("copy");
  ta.remove();
  return ok;
}